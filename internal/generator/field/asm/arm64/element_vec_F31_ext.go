// GenerateF31Ext generates the NEON kernels of the extension towers of 31-bit fields. The towers are fixed to
// u² = 3 and ξ = 1 + u, which among the 31-bit fields only KoalaBear satisfies. The modulus and the Montgomery
// constant are read from the constants q and mu of the package that includes the assembly.
func GenerateF31Ext(w io.Writer) error {
	f := NewFFArm64(w, 1)

	f.WriteLn("")
	f.Comment("Code generated by gnark-crypto/generator. DO NOT EDIT.")
	f.Comment("Refer to the generator for more documentation.")
	f.WriteLn("")
	f.WriteLn("#include \"textflag.h\"")
	f.WriteLn("#include \"funcdata.h\"")
	f.WriteLn("#include \"go_asm.h\"")
	f.WriteLn("")

	f.generateMulVecE6()

	return nil
}

// vld3P emits a post-incrementing VLD3 with D2 arrangement: it loads 6 consecutive 64-bit words from ptr and
// deinterleaves them into 3 registers, which must be consecutive. Register k holds words k and 3+k.
func (f *FFArm64) vld3P(ptr arm64.Register, dst0, dst1, dst2 arm64.VectorRegister, comment string) {
	f.WriteLn(fmt.Sprintf("\tVLD3.P 48(%s), [%s.D2, %s.D2, %s.D2] // %s", ptr, dst0, dst1, dst2, comment))
}

// vst3P emits a post-incrementing VST3 with D2 arrangement, the inverse of vld3P. The registers must be consecutive.
func (f *FFArm64) vst3P(src0, src1, src2 arm64.VectorRegister, ptr arm64.Register, comment string) {
	f.WriteLn(fmt.Sprintf("\tVST3.P [%s.D2, %s.D2, %s.D2], 48(%s) // %s", src0, src1, src2, ptr, comment))
}

// vzip1 emits dst = ZIP1(n, m) on S4 arrangements: dst = [n0, m0, n1, m1]. The Go assembler takes the operands of
// VZIP1 and VZIP2 in the order m, n, dst.
func (f *FFArm64) vzip1(n, m, dst arm64.VectorRegister, comment string) {
	f.WriteLn(fmt.Sprintf("\tVZIP1 %s.S4, %s.S4, %s.S4 // %s", m, n, dst, comment))
}

// vzip2 emits dst = ZIP2(n, m) on S4 arrangements: dst = [n2, m2, n3, m3].
func (f *FFArm64) vzip2(n, m, dst arm64.VectorRegister, comment string) {
	f.WriteLn(fmt.Sprintf("\tVZIP2 %s.S4, %s.S4, %s.S4 // %s", m, n, dst, comment))
}

// generateMulVecE6 emits vectorMul_E6_neon(res, a, b *E6, N uint64), the element-wise product of two vectors of E6.
// N must be a multiple of 4.
//
// With the tower E2 = Fp[u]/(u² − 3), E6 = E2[v]/(v³ − ξ), ξ = 1 + u, which only holds for KoalaBear, the algorithm
// is that of vectorMul_E6_avx512: Karatsuba at both levels, so 6 E2 products of 3 base products each. Writing X = X0 + X1·v + X2·v², Tj = Xj·Yj,
//
//	c0 = T0 + ξ·((X1+X2)(Y1+Y2) − T1 − T2)
//	c1 = (X0+X1)(Y0+Y1) − T0 − T1 + ξ·T2
//	c2 = (X0+X2)(Y0+Y2) − T0 − T2 + T1
//
// Every intermediate is fully reduced.
//
// An iteration processes 4 E6 (96 bytes) of a and of b. Two VLD3 with D2 arrangement load 2 E6 each and deinterleave
// them so that register k holds the E2 coordinate Bk of both; UZP1 and UZP2 on the two loads then split each Bk
// into its coordinates Ak,0 and Ak,1 of the 4 elements. The results go back through ZIP1/ZIP2 and VST3.
func (f *FFArm64) generateMulVecE6() {
	f.Comment("vectorMul_E6_neon(res, a, b *E6, N uint64)")
	f.Comment("N must be a multiple of 4.")
	f.Comment("")
	f.Comment("Karatsuba at both levels of the tower E2 = Fp[u]/(u² - 3), E6 = E2[v]/(v³ - ξ), ξ = 1 + u:")
	f.Comment("  c0 = T0 + ξ·((X1+X2)(Y1+Y2) - T1 - T2)")
	f.Comment("  c1 = (X0+X1)(Y0+Y1) - T0 - T1 + ξ·T2")
	f.Comment("  c2 = (X0+X2)(Y0+Y2) - T0 - T2 + T1")
	registers := f.FnHeader("vectorMul_E6_neon", 0, 32)
	defer f.AssertCleanStack(0, 0)

	// registers
	resPtr := registers.Pop()
	aPtr := registers.Pop()
	bPtr := registers.Pop()
	n := registers.Pop()

	// load arguments
	f.LDP("res+0(FP)", resPtr, aPtr)
	f.LDP("b+16(FP)", bPtr, n)
	f.WriteLn(fmt.Sprintf("\tLSR $2, %s // 4 elements per iteration", n))

	// vector registers. VLD3 and VST3 need consecutive registers.
	var a, b, t [6]arm64.VectorRegister // coordinates of X and Y, and of T0, T1, T2
	for k := range a {
		a[k] = arm64.VectorRegister(fmt.Sprintf("V%d", k))
		b[k] = arm64.VectorRegister(fmt.Sprintf("V%d", 6+k))
		t[k] = arm64.VectorRegister(fmt.Sprintf("V%d", 12+k))
	}
	p, mu := arm64.V18, arm64.V19
	cHi, qm, qpHi, underflow := arm64.V20, arm64.V21, arm64.V22, arm64.V23 // Montgomery scratch, also modular add/sub scratch
	free := []arm64.VectorRegister{arm64.V24, arm64.V25, arm64.V26, arm64.V27, arm64.V28, arm64.V29, arm64.V30, arm64.V31}
	pop := func() arm64.VectorRegister {
		r := free[len(free)-1]
		free = free[:len(free)-1]
		return r
	}
	push := func(rs ...arm64.VectorRegister) { free = append(free, rs...) }

	// constants
	f.VMOVS("$const_q", p)
	f.VDUP(p.SAt(0), p.S4(), "broadcast q")
	tmp := registers.Pop()
	f.MOVD("$const_mu", tmp)
	f.VDUP(tmp, mu.S4(), "broadcast mu")
	registers.Push(tmp)

	add := func(dst, x, y arm64.VectorRegister) { f.modAddF31(dst, x, y, p, underflow) }
	sub := func(dst, x, y arm64.VectorRegister) { f.modSubF31(dst, x, y, p, underflow) }
	mul := func(dst, x, y arm64.VectorRegister) { f.montMulF31(dst, x, y, p, mu, cHi, qm, qpHi, underflow) }

	// e2Mul sets (re, im) = (xr + xi·u)(yr + yi·u); x and y are kept.
	e2Mul := func(xr, xi, yr, yi, re, im arm64.VectorRegister) {
		s1, s2 := pop(), pop()
		mul(re, xr, yr) // m0
		mul(s1, xi, yi) // m1
		add(s2, xr, xi)
		add(im, yr, yi)
		mul(im, s2, im) // m2
		sub(im, im, re)
		sub(im, im, s1) // im = m2 - m0 - m1
		add(s2, s1, s1)
		add(s2, s2, s1)
		add(re, re, s2) // re = m0 + 3·m1
		push(s1, s2)
	}

	// e2MulInPlace sets (xr, xi) = (xr + xi·u)(yr + yi·u); y is clobbered.
	e2MulInPlace := func(xr, xi, yr, yi arm64.VectorRegister) {
		s1, s2 := pop(), pop()
		mul(s1, xr, yr) // m0
		mul(s2, xi, yi) // m1
		add(xr, xr, xi)
		add(yr, yr, yi)
		mul(xi, xr, yr) // m2
		sub(xi, xi, s1)
		sub(xi, xi, s2) // im = m2 - m0 - m1
		add(yr, s2, s2)
		add(yr, yr, s2)
		add(xr, s1, yr) // re = m0 + 3·m1
		push(s1, s2)
	}

	// cross returns (Xj + Xk)(Yj + Yk) - Tj - Tk in two fresh registers.
	cross := func(j, k int) (mr, mi arm64.VectorRegister) {
		mr, mi = pop(), pop()
		yr, yi := pop(), pop()
		add(mr, a[2*j], a[2*k])
		add(mi, a[2*j+1], a[2*k+1])
		add(yr, b[2*j], b[2*k])
		add(yi, b[2*j+1], b[2*k+1])
		e2MulInPlace(mr, mi, yr, yi)
		push(yr, yi)
		sub(mr, mr, t[2*j])
		sub(mr, mr, t[2*k])
		sub(mi, mi, t[2*j+1])
		sub(mi, mi, t[2*k+1])
		return
	}

	// mulByXi sets (re, im) = ξ·(r + i·u) = (r + 3i) + (r + i)·u.
	mulByXi := func(r, i, re, im arm64.VectorRegister) {
		add(re, i, i)
		add(re, re, i)
		add(re, re, r)
		add(im, r, i)
	}

	// load4 loads 4 E6 from ptr into the 6 coordinate registers x, clobbering t.
	load4 := func(ptr arm64.Register, x [6]arm64.VectorRegister, name string) {
		f.vld3P(ptr, t[0], t[1], t[2], "load B0, B1, B2 of elements 0 and 1 of "+name)
		f.vld3P(ptr, t[3], t[4], t[5], "load B0, B1, B2 of elements 2 and 3 of "+name)
		for k := range 3 {
			f.VUZP1(t[k], t[3+k], x[2*k], fmt.Sprintf("%s.A%d,0 of the 4 elements", name, k))
			f.VUZP2(t[k], t[3+k], x[2*k+1], fmt.Sprintf("%s.A%d,1 of the 4 elements", name, k))
		}
	}

	f.Loop(n, func() {
		load4(aPtr, a, "a")
		load4(bPtr, b, "b")

		for j := range 3 {
			e2Mul(a[2*j], a[2*j+1], b[2*j], b[2*j+1], t[2*j], t[2*j+1])
		}

		// c2 = (X0+X2)(Y0+Y2) - T0 - T2 + T1
		c2r, c2i := cross(0, 2)
		add(c2r, c2r, t[2])
		add(c2i, c2i, t[3])

		// c1 = (X0+X1)(Y0+Y1) - T0 - T1 + ξ·T2
		c1r, c1i := cross(0, 1)
		xr, xi := pop(), pop()
		mulByXi(t[4], t[5], xr, xi)
		add(c1r, c1r, xr)
		add(c1i, c1i, xi)
		push(xr, xi, a[0], a[1], b[0], b[1])

		// c0 = T0 + ξ·((X1+X2)(Y1+Y2) - T1 - T2)
		mr, mi := cross(1, 2)
		c0r, c0i := pop(), pop()
		mulByXi(mr, mi, c0r, c0i)
		add(c0r, c0r, t[0])
		add(c0i, c0i, t[1])
		push(mr, mi)

		// store: B_k = (c_k,0, c_k,1) of the 4 elements go back to E2 lanes, then to the interleaved layout.
		// The T registers are dead and hold the zipped results.
		res := [3][2]arm64.VectorRegister{{c0r, c0i}, {c1r, c1i}, {c2r, c2i}}
		for k := range 3 {
			f.vzip1(res[k][0], res[k][1], t[k], fmt.Sprintf("B%d of elements 0 and 1", k))
			f.vzip2(res[k][0], res[k][1], t[3+k], fmt.Sprintf("B%d of elements 2 and 3", k))
		}
		f.vst3P(t[0], t[1], t[2], resPtr, "store elements 0 and 1")
		f.vst3P(t[3], t[4], t[5], resPtr, "store elements 2 and 3")
		push(c0r, c0i, c1r, c1i, c2r, c2i)
	})

	registers.Push(resPtr, aPtr, bPtr, n)

	f.RET()
}
